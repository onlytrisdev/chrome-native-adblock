    public static string CurrentLanguage { get; private set; } = Vietnamese;

    public static void Initialize()
    {
        var defaultLang = CultureInfo.CurrentUICulture.TwoLetterISOLanguageName.ToLowerInvariant() switch
        {
            "vi" => Vietnamese,
            "zh" => Chinese,
            _ => English
        };

        var saved = TryReadSavedLanguage();
        CurrentLanguage = NormalizeLanguage(saved ?? defaultLang);
    }

    public static void SetLanguage(string language)
    {
        var normalized = NormalizeLanguage(language);
        if (string.Equals(CurrentLanguage, normalized, StringComparison.OrdinalIgnoreCase))
        {
            return;
        }

        CurrentLanguage = normalized;
        try
        {
            var dir = Path.GetDirectoryName(SettingsPath);
            if (!string.IsNullOrWhiteSpace(dir))
            {
                Directory.CreateDirectory(dir);
            }
            File.WriteAllText(SettingsPath, CurrentLanguage);
        }
        catch { }

        LanguageChanged?.Invoke();
    }

    public static string Text(string key, params object[] arguments)
    {
        if (Translations.TryGetValue(CurrentLanguage, out var langDict) &&
            langDict.TryGetValue(key, out var text))
        {
            return arguments.Length == 0 ? text : string.Format(CultureInfo.InvariantCulture, text, arguments);
        }

        if (Translations[English].TryGetValue(key, out var enText))
        {
            return arguments.Length == 0 ? enText : string.Format(CultureInfo.InvariantCulture, enText, arguments);
        }

        return key;
    }

    private static string? TryReadSavedLanguage()
    {
        try
        {
            if (File.Exists(SettingsPath))
            {
                var content = File.ReadAllText(SettingsPath).Trim();
                if (!string.IsNullOrWhiteSpace(content))
                {
                    return content;
                }
            }
        }
        catch { }

        return null;
    }

    private static string NormalizeLanguage(string language)
    {
        if (string.Equals(language, Vietnamese, StringComparison.OrdinalIgnoreCase)) return Vietnamese;
        if (string.Equals(language, Chinese, StringComparison.OrdinalIgnoreCase)) return Chinese;
        return English;
    }
